def xorshift32_stream(seed, n):
    x = seed & 0xffffffff
    if x == 0:
        x = 0xdeadbeef
    out = bytearray()
    while len(out) < n:
        x ^= (x << 13) & 0xffffffff
        x ^= (x >> 17)
        x ^= (x << 5) & 0xffffffff
        x &= 0xffffffff
        out += x.to_bytes(4, "little")
    return bytes(out[:n])


def decode_flag_statically():
    keystream = xorshift32_stream(VM_TARGET, len(FLAG_CT))
    return bytes(a ^ b for a, b in zip(FLAG_CT, keystream)).decode()


def symbolic_run(input_bytes):
    reg = [z3.BitVecVal(0, 32) for _ in range(4)]
    pc = 0
    ok = z3.BoolVal(False)
    prog = VM_PROG
    while pc < len(prog):
        op = prog[pc]; pc += 1
        if op == 1:
            r = prog[pc]; pc += 1
            imm = int.from_bytes(prog[pc:pc + 4], "little"); pc += 4
            reg[r] = z3.BitVecVal(imm, 32)
        elif op == 2:
            r = prog[pc]; pc += 1
            idx = prog[pc]; pc += 1
            reg[r] = z3.ZeroExt(24, input_bytes[idx])
        elif op == 3:
            d = prog[pc]; pc += 1
            s = prog[pc]; pc += 1
            reg[d] = reg[d] + reg[s]
        elif op == 4:
            d = prog[pc]; pc += 1
            s = prog[pc]; pc += 1
            reg[d] = reg[d] ^ reg[s]
        elif op == 5:
            d = prog[pc]; pc += 1
            imm = prog[pc]; pc += 1
            reg[d] = z3.RotateLeft(reg[d], imm & 31)
        elif op == 6:
            d = prog[pc]; pc += 1
            s = prog[pc]; pc += 1
            reg[d] = reg[d] * reg[s]
        elif op == 7:
            r = prog[pc]; pc += 1
            imm = int.from_bytes(prog[pc:pc + 4], "little"); pc += 4
            ok = (reg[r] == z3.BitVecVal(imm, 32))
        elif op == 8:
            break
    return ok


def find_a_valid_serial():
    s = z3.Solver()
    inp = [z3.BitVec(f"b{i}", 8) for i in range(SERIAL_LEN)]
    for b in inp:
        s.add(b >= 0x21, b <= 0x7e)
    s.add(symbolic_run(inp))
    if s.check() != z3.sat:
        raise SystemExit("unsat - shouldn't happen")
    m = s.model()
    return bytes(m[b].as_long() for b in inp).decode()


