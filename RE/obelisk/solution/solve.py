#!/usr/bin/env python3
"""
Solve for Obelisk (RE, insane).

Two independent ways to get the flag; this does both and cross-checks them.

1. STATIC: the interpreter loop in the binary is generic - the actual check
   is data (vm_prog[]), not code. Pull the final CMP's 32-bit immediate out
   of that array by hand (last 6 bytes before the HALT opcode): that's the
   value the VM's accumulator must equal. The flag's ciphertext (flag_ct[])
   is XORed against an xorshift32 stream seeded with that exact value - so
   you never actually have to satisfy the check to get the flag, just find
   the constant and replay the same keystream generator.

2. DYNAMIC: if you'd rather see the binary print it itself, model the VM's
   ~8 opcodes symbolically in z3 (BitVecs for the 20 input bytes, replay
   every ADD/XOR/ROL/MUL exactly as the interpreter does) and ask for any
   input that makes the final register equal the target constant. Feed
   that to the binary. (Run it outside gdb - PTRACE_TRACEME in main()
   bails out the moment a debugger attaches.)
"""
