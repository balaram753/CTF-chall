static uint32_t rotl32(uint32_t x, uint32_t n) {
    n &= 31;
    return (x << n) | (x >> (32 - n));
}

/* returns 1 if the serial hashes to the value the program was compiled with */
static int vm_run(const unsigned char *input) {
    uint32_t reg[4] = {0, 0, 0, 0};
    size_t pc = 0;
    int ok = 0;

    while (pc < VM_PROG_LEN) {
        unsigned char op = vm_prog[pc++];
        switch (op) {
        case OP_LOADI: {
            unsigned char r = vm_prog[pc++];
            uint32_t imm;
            memcpy(&imm, &vm_prog[pc], 4);
            pc += 4;
            reg[r] = imm;
            break;
        }
        case OP_LOADB: {
            unsigned char r = vm_prog[pc++];
            unsigned char idx = vm_prog[pc++];
            reg[r] = input[idx];
            break;
        }
        case OP_ADD: {
            unsigned char d = vm_prog[pc++];
            unsigned char s = vm_prog[pc++];
            reg[d] += reg[s];
            break;
        }
        case OP_XOR: {
            unsigned char d = vm_prog[pc++];
            unsigned char s = vm_prog[pc++];
            reg[d] ^= reg[s];
            break;
        }
        case OP_ROL: {
            unsigned char d = vm_prog[pc++];
            unsigned char imm = vm_prog[pc++];
            reg[d] = rotl32(reg[d], imm);
            break;
        }
        case OP_MUL: {
            unsigned char d = vm_prog[pc++];
            unsigned char s = vm_prog[pc++];
            reg[d] *= reg[s];
            break;
        }
        case OP_CMP: {
            unsigned char r = vm_prog[pc++];
            uint32_t imm;
            memcpy(&imm, &vm_prog[pc], 4);
            pc += 4;
            ok = (reg[r] == imm);
            break;
        }
        case OP_HALT:
            return ok;
        default:
            return 0;
        }
    }
    return ok;
}

/* keystream used both here and to build flag_ct at compile time */
static void xorshift32_stream(uint32_t seed, unsigned char *out, size_t n) {
    uint32_t x = seed ? seed : 0xdeadbeefu;
    size_t i = 0;
    while (i < n) {
        x ^= (x << 13);
        x ^= (x >> 17);
        x ^= (x << 5);
        unsigned char b0 = x & 0xff, b1 = (x >> 8) & 0xff, b2 = (x >> 16) & 0xff, b3 = (x >> 24) & 0xff;
        if (i < n) out[i++] = b0;
        if (i < n) out[i++] = b1;
        if (i < n) out[i++] = b2;
        if (i < n) out[i++] = b3;
    }
}

/* seed is recovered from the VM's own final register value -
   see vm_run's OP_CMP target, which is baked into the bytecode itself */
static void reveal_flag(uint32_t seed) {
    unsigned char keystream[FLAG_CT_LEN];
    unsigned char flag[FLAG_CT_LEN + 1];
    xorshift32_stream(seed, keystream, FLAG_CT_LEN);
    for (size_t i = 0; i < FLAG_CT_LEN; i++) {
        flag[i] = flag_ct[i] ^ keystream[i];
    }
    flag[FLAG_CT_LEN] = '\0';
    printf("%s\n", flag);
}

/* mirrors the final CMP operand in vm_prog - the interpreter checks the
   register against this same value, it isn't derived independently */
#define VM_TARGET 0xb08ad79fu

static int being_traced(void) {
    return ptrace(PTRACE_TRACEME, 0, 1, 0) < 0;
}

static int valid_charset(const char *s, size_t n) {
    for (size_t i = 0; i < n; i++) {
        if (s[i] < 0x21 || s[i] > 0x7e) {
            return 0;
        }
    }
    return 1;
}

int main(void) {
    char input[64];

    if (being_traced()) {
        puts("tamper detected.");
        return 1;
    }

    puts("OBELISK");
    puts("A sealed relic. It only responds to the correct rite.");
    printf("> ");
    fflush(stdout);

    if (!fgets(input, sizeof(input), stdin)) {
        return 1;
    }
    input[strcspn(input, "\n")] = '\0';

    if (strlen(input) != SERIAL_LEN || !valid_charset(input, SERIAL_LEN)) {
        puts("The relic stays silent.");
        return 1;
    }

    if (!vm_run((const unsigned char *)input)) {
        puts("The relic stays silent.");
        return 1;
    }

    puts("The seal breaks.\n");
    reveal_flag(VM_TARGET);
    return 0;
}
