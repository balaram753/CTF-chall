#!/usr/bin/env python3
"""
Ziggurat reference solution.

Intended path:
  1. The binary refuses gdb (ptrace TRACEME) -> reverse it statically.
  2. Inside you find a small VM, but the bytecode array is ciphertext. It is
     decrypted one byte at a time as it's fetched, using a rolling key seeded
     with the constant VM_SEED. There are no back-jumps, so fetch order == byte
     order: reimplement the decryptor and you recover the real program.
  3. The recovered program loads six 32-bit lanes from the 24-char input, runs
     four ARX rounds that mix the lanes together (add-const, cross-lane xor,
     multiply-by-odd, rotate), and finally CMPs each lane against a constant.
     The cross-lane mixing + multiply means you can't peel it byte by byte, so
     hand the whole thing to z3.
  4. The flag is NOT xored against a constant in the binary. Its key is derived
     from the serial itself (two FNV-1a-64 lanes -> xorshift128 keystream), so
     you must recover the actual serial first. Then decrypt the flag.

Only three facts were lifted from the binary by hand: VM_SEED, ENC_PROG (the
encrypted bytecode) and FLAG_CT. Everything else is derived here.
"""

